// Test GIF generation — create a small animated GIF from a static image
// ===========================================================================

/// Generate a test animated GIF by translating the source image across
/// multiple frames — this produces a file that can be fed back as GIF input.
fn save_test_gif(img_path: &str, gif_path: &str) -> Result<(), Box<dyn std::error::Error>> {
    let img = image::open(img_path)?;
    let (width, height) = img.dimensions();
    let rgb_base = img.to_rgb8();

    let file = File::create(gif_path)?;
    let mut encoder = GifEncoder::new(file);
    encoder.set_repeat(Repeat::Infinite)?;

    for k in 0..SYNTH_NUM_FRAMES {
        let shift_x = (k as f32 * SYNTH_DX).round() as i32;
        let shift_y = (k as f32 * SYNTH_DY).round() as i32;

        let mut rgba = RgbaImage::new(width, height);
        for y in 0..height {
            for x in 0..width {
                let src_x = (x as i32 - shift_x).clamp(0, width as i32 - 1) as u32;
                let src_y = (y as i32 - shift_y).clamp(0, height as i32 - 1) as u32;
                let px = rgb_base.get_pixel(src_x, src_y);
                rgba.put_pixel(x, y, image::Rgba([px[0], px[1], px[2], 255]));
            }
        }

        let delay = image::Delay::from_numer_denom_ms(100, 1); // 10 fps
        let frame = Frame::from_parts(rgba, 0, 0, delay);
        encoder.encode_frame(frame)?;
    }

    Ok(())
}

// ===========================================================================
// Drawing helpers
// ===========================================================================

/// Save an annotated copy of the base image showing tracked feature trails.
fn save_tracked_frame(
    base: &image::RgbImage,
    tracks: &[Track],
    path: &str,
) -> Result<(), Box<dyn std::error::Error>> {
    let mut out: ImageBuffer<Rgb<u8>, Vec<u8>> = base.clone();

    for (ti, track) in tracks.iter().enumerate() {
        let color = track_color(ti);
        let pts = &track.positions;

        // Draw trail segments.
        for w in pts.windows(2) {
            draw_line(
                &mut out,
                w[0].x as i32,
                w[0].y as i32,
                w[1].x as i32,
                w[1].y as i32,
                color,
            );
        }

        // Draw circle at head position.
        if let Some(head) = pts.last() {
            draw_circle(&mut out, head.x as i32, head.y as i32, 3, color);
        }
    }

    DynamicImage::ImageRgb8(out).save(path)?;
    Ok(())
}

/// Assign a visually distinct colour per track via golden-ratio hue cycling.
fn track_color(index: usize) -> Rgb<u8> {
    let hue = (index as f32 * 137.508) % 360.0;
    hsv_to_rgb(hue, 0.9, 0.95)
}

/// HSV → RGB conversion.
fn hsv_to_rgb(h: f32, s: f32, v: f32) -> Rgb<u8> {
    let c = v * s;
    let x = c * (1.0 - ((h / 60.0) % 2.0 - 1.0).abs());
    let m = v - c;
    let (r1, g1, b1) = match (h / 60.0).floor() as i32 % 6 {
        0 => (c, x, 0.0),
        1 => (x, c, 0.0),
        2 => (0.0, c, x),
        3 => (0.0, x, c),
        4 => (x, 0.0, c),
        _ => (c, 0.0, x),
    };
    Rgb([
        ((r1 + m) * 255.0) as u8,
        ((g1 + m) * 255.0) as u8,
        ((b1 + m) * 255.0) as u8,
    ])
}

/// Bresenham line drawing.
fn draw_line(
    img: &mut image::RgbImage,
    mut x0: i32,
    mut y0: i32,
    x1: i32,
    y1: i32,
    color: Rgb<u8>,
) {
    let (w, h) = (img.width() as i32, img.height() as i32);
    let dx = (x1 - x0).abs();
    let dy = -(y1 - y0).abs();
    let sx = if x0 < x1 { 1 } else { -1 };
    let sy = if y0 < y1 { 1 } else { -1 };
    let mut err = dx + dy;
    loop {
        if x0 >= 0 && x0 < w && y0 >= 0 && y0 < h {
            img.put_pixel(x0 as u32, y0 as u32, color);
        }
        if x0 == x1 && y0 == y1 {
            break;
        }
        let e2 = 2 * err;
        if e2 >= dy {
            err += dy;
            x0 += sx;
        }
        if e2 <= dx {
            err += dx;
            y0 += sy;
        }
    }
}

/// Filled circle drawing.
fn draw_circle(img: &mut image::RgbImage, cx: i32, cy: i32, radius: i32, color: Rgb<u8>) {
    let (w, h) = (img.width() as i32, img.height() as i32);
    for dy in -radius..=radius {
        for dx in -radius..=radius {
            if dx * dx + dy * dy <= radius * radius {
                let px = cx + dx;
                let py = cy + dy;
                if px >= 0 && px < w && py >= 0 && py < h {
                    img.put_pixel(px as u32, py as u32, color);
                }
            }
        }
    }
}
